"""Pydantic v2 Schema Definitions for Real-Time Financial Risk Inference API.

Implements strict validation contracts for incoming transaction payloads,
local TreeSHAP attribution outputs, and AgentCore compliance audit memos.
"""

from __future__ import annotations

from datetime import datetime, timezone
from typing import Optional

from pydantic import BaseModel, Field, field_validator


class TransactionRequest(BaseModel):
    """Incoming credit card payment transaction payload."""

    transaction_id: str = Field(..., description="Unique transaction reference ID (e.g. TX_20261015_0001)")
    timestamp: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat(), description="ISO8601 transaction timestamp")
    customer_id: str = Field(..., description="Unique customer identifier")
    card_number_masked: str = Field(..., description="PCI-compliant masked PAN (e.g. 411111******1234)")
    transaction_amount: float = Field(..., gt=0.0, description="Transaction monetary amount in USD")
    card_velocity_1h: int = Field(..., ge=0, description="Number of transactions on this card in the last 1 hour")
    card_velocity_24h: int = Field(..., ge=0, description="Number of transactions on this card in the last 24 hours")
    distance_from_home_km: float = Field(..., ge=0.0, description="Distance from cardholder primary residence in kilometers")
    merchant_risk_score: float = Field(..., ge=0.0, le=1.0, description="Merchant fraud risk probability score [0.0 - 1.0]")
    is_international: int = Field(..., ge=0, le=1, description="1 if merchant is outside home country, else 0")
    device_trust_score: float = Field(..., ge=0.0, le=1.0, description="Device fingerprint reputation score [0.0 - 1.0]")
    account_age_days: int = Field(..., ge=0, description="Age of the customer account in days")
    customer_age_group: str = Field(default="36-50", description="Demographic age bucket for audit tracking")

    @field_validator("card_velocity_24h")
    @classmethod
    def validate_velocity(cls, v: int, info) -> int:
        v1h = info.data.get("card_velocity_1h", 0)
        if v < v1h:
            raise ValueError(f"card_velocity_24h ({v}) cannot be less than card_velocity_1h ({v1h})")
        return v

    model_config = {
        "json_schema_extra": {
            "example": {
                "transaction_id": "TX_20261015_0099412",
                "customer_id": "CUST_004128",
                "card_number_masked": "411111******8821",
                "transaction_amount": 450.00,
                "card_velocity_1h": 3,
                "card_velocity_24h": 7,
                "distance_from_home_km": 850.5,
                "merchant_risk_score": 0.82,
                "is_international": 1,
                "device_trust_score": 0.18,
                "account_age_days": 45,
                "customer_age_group": "26-35",
            }
        }
    }


class ShapContribution(BaseModel):
    """Local SHAP feature attribution contribution for individual prediction explainability."""

    feature_name: str = Field(..., description="Name of the input feature")
    feature_value: float = Field(..., description="Actual value passed in request")
    shap_value: float = Field(..., description="Directional SHAP impact (+ indicates higher risk)")
    description: str = Field(..., description="Human-readable explanation of risk influence")


class ComplianceAuditSummary(BaseModel):
    """Structured AML/KYC audit memo generated by Amazon Bedrock AgentCore."""

    audit_triggered: bool = Field(..., description="True if fraud probability exceeded audit threshold (0.85)")
    risk_tier: str = Field(..., description="Categorical risk tier: LOW, MEDIUM, HIGH, CRITICAL")
    cited_policy_section: str = Field(..., description="Specific regulatory section cited (e.g. FinCEN §1010.311)")
    recommended_action: str = Field(..., description="Action: APPROVE, STEP_UP_AUTH, SUSPEND_CARD, FILE_SAR")
    trace_id: str = Field(..., description="AgentCore execution trace identifier")
    compliance_narrative: str = Field(..., description="Audit narrative justifying regulatory decision")


class PredictionResponse(BaseModel):
    """Final real-time response payload returned by /predict endpoint."""

    transaction_id: str
    fraud_probability: float = Field(..., ge=0.0, le=1.0)
    is_fraud_flagged: bool
    risk_tier: str
    top_shap_contributions: list[ShapContribution]
    compliance_audit: Optional[ComplianceAuditSummary] = None
    model_version: str
    latency_ms: float


class HealthResponse(BaseModel):
    """Service health and model metadata check."""

    status: str
    model_loaded: bool
    model_name: str
    model_version: str
    environment: str
    timestamp: str
